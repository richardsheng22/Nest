// Brings Erwu over from Bloom, so both games draw the same painted cat.
//   node tools/sync-erwu.cjs [path/to/bloom]      (default: ../bloom, or BLOOM_DIR)
// Bloom is the source of truth for Erwu: her sheets are generated and packed there by
// Bloom's tools/build-art.cjs. This copies the packed atlas and writes erwu-art.js with
// where each frame sits. Re-run it whenever Bloom's Erwu changes.
const fs = require('node:fs');
const path = require('node:path');
const { execSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const bloom = path.resolve(process.argv[2] || process.env.BLOOM_DIR || path.join(root, '..', 'bloom'));

const ART = require(path.join(bloom, 'art-manifest.js'));
if (!ART.erwu) throw new Error(`No Erwu in ${bloom}/art-manifest.js`);
fs.mkdirSync(path.join(root, 'assets'), { recursive: true });
fs.copyFileSync(path.join(bloom, ART.erwu.src), path.join(root, 'assets', 'erwu.webp'));

let from = 'Bloom';
try { from += ' ' + execSync('git rev-parse --short HEAD', { cwd: bloom }).toString().trim(); } catch {}
const out = { src: 'assets/erwu.webp', size: ART.erwu.size, frames: ART.erwu.frames };
fs.writeFileSync(path.join(root, 'erwu-art.js'),
  `/* Generated by tools/sync-erwu.cjs from ${from}. Do not edit by hand. */\n` +
  `/* frame: [x, y, w, h, anchorX, anchorY, ...]; the anchor is where she meets the ground */\n` +
  `window.ErwuArt = ${JSON.stringify(out)};\n`);
console.log(`Erwu synced from ${from}: ${Object.keys(out.frames).length} frames`);
